import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
import { createServer, preview } from 'vite';

const dev = await createServer({ server: { host: '127.0.0.1', port: 0 } });
await dev.listen();
const url = server => `http://127.0.0.1:${server.httpServer.address().port}/`;
let browser;
let release;
try {
  browser = await chromium.launch({ channel: 'msedge' });
  const page = await browser.newPage({ viewport: { width: 1360, height: 900 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const button = (name, scope = page) => scope.getByRole('button', { name, exact: true });
  const select = (name, value) => page.getByLabel(name).and(page.locator('select')).selectOption(value);
  const cell = (x, y) => page.getByRole('button', { name: new RegExp(`^${x + 1}列${y + 1}行 `) });
  const read = () => page.evaluate(() => JSON.parse(window.render_game_to_text()));
  const data = () => page.evaluate(() => Object.fromEntries(Object.entries(localStorage)));
  const heading = name => page.getByRole('heading', { name, exact: true }).waitFor();
  const resume = () => button('继续战局').click();
  const menu = () => button('返回主菜单', page.locator('#overlay')).click();

  await mkdir('test-results', { recursive: true });
  await page.goto(url(dev));
  await select('战役', 'march');
  await button('开始部署').click();
  await page.locator('#hand [data-card="watch"]').first().click();
  await cell(5, 2).click();
  await page.evaluate(() => localStorage.setItem('nine-kingdoms-chronicle-v1', JSON.stringify({
    version: 1, merit: 1, expeditions: 1, victories: 0, records: ['0'.repeat(32)],
  })));
  const normal = await data();
  await button('开始战斗').click();
  await button('暂停战斗').click();
  await menu();
  await select('战役', 'march');
  await page.locator('#seed-input').fill('42');
  await button('打开调试沙盒').click();
  await heading('开发调试沙盒');
  let snapshot = await read();
  assert.equal(snapshot.seed, 42);
  assert.equal(snapshot.chronicleId, null);
  assert.deepEqual(snapshot.buildings, []);
  await button('设置').click();
  await page.getByLabel('关闭音效').check();
  await select('动态效果', 'off');
  await select('帧率上限', '144');
  await button('返回', page.locator('#overlay')).click();
  await page.getByLabel('无限补给').check();
  assert.deepEqual((await read()).wallet, { gold: 25, food: 15, wood: 18, mana: 10 });
  await select('目标波次', '5');
  await button('跳转波次').click();
  assert.equal((await read()).wave, 5);
  await select('军令', 'sentinel');
  await button('加入军令').click();
  await page.locator('#hand [data-card="sentinel"]').first().click();
  await cell(8, 3).click();
  assert.deepEqual((await read()).wallet, { gold: 25, food: 15, wood: 18, mana: 10 });
  assert.deepEqual(await data(), normal);

  await button('开始战斗').click();
  await button('暂停时钟').click();
  await select('敌军', 'marshal');
  await button('安排敌军').click();
  const tick = (await read()).tick;
  await button('推进模拟').click();
  snapshot = await read();
  assert.equal(snapshot.tick, tick + 1);
  assert.equal(snapshot.paused, true);
  const boss = snapshot.actors.find(actor => actor.def === 'marshal');
  assert.ok(boss);
  assert.equal(boss.hp, 88);
  await select('场上单位', String(boss.id));
  await select('属性', 'hp');
  await page.getByLabel('数值', { exact: true }).fill('999');
  await button('应用属性').click();
  await button('安排敌军').click();
  await button('推进模拟').click();
  const marshals = (await read()).actors.filter(actor => actor.def === 'marshal');
  assert.deepEqual(marshals.map(actor => actor.hp), [999, 88]);
  assert.match(await page.locator('.sandbox-data').innerText(), /本波命中.*伤害.*治疗/);
  await page.screenshot({ path: 'test-results/sandbox.png', fullPage: true });
  await page.getByLabel('推进步数').fill('1000');
  await button('推进模拟').click();
  await heading('防线失守');
  assert.equal((await read()).keepHp, 0);
  assert.deepEqual(await data(), normal);

  await menu();
  await page.waitForURL(url(dev));
  await resume();
  snapshot = await read();
  assert.equal(snapshot.seed, 119);
  assert.deepEqual(snapshot.buildings.map(building => building.def), ['watch']);
  assert.deepEqual(await data(), normal);

  const corrupted = '{invalid archive';
  await page.evaluate(value => localStorage.setItem('nine-kingdoms-run-v1', value), corrupted);
  await page.reload();
  assert.match(await page.locator('#overlay [role="status"]').innerText(), /从备用进度继续/);
  assert.equal((await data())['nine-kingdoms-run-v1'], corrupted);
  await page.screenshot({ path: 'test-results/checkpoint-recovery.png', fullPage: true });
  await button('开始部署').click();
  assert.match(await page.locator('#replace-run-current').innerText(), /灰旗远征.*钢铁王国.*种子 119/);
  await page.keyboard.press('Escape');
  assert.equal((await data())['nine-kingdoms-run-v1'], corrupted);
  await resume();
  assert.deepEqual((await read()).buildings.map(building => building.def), ['watch']);
  const restoredStorage = await data();
  assert.deepEqual(JSON.parse(restoredStorage['nine-kingdoms-run-v1']), JSON.parse(normal['nine-kingdoms-run-v1']));
  assert.equal(restoredStorage['nine-kingdoms-run-v1'], restoredStorage['nine-kingdoms-run-backup-v1']);
  assert.equal(restoredStorage['nine-kingdoms-chronicle-v1'], normal['nine-kingdoms-chronicle-v1']);

  await page.evaluate(value => {
    localStorage.setItem('nine-kingdoms-run-v1', value);
    localStorage.setItem('nine-kingdoms-run-backup-v1', value);
  }, corrupted);
  await page.reload();
  assert.equal(await button('继续战局').count(), 0);
  assert.match(await page.locator('#overlay [role="status"]').innerText(), /存档无法读取/);
  assert.equal((await data())['nine-kingdoms-run-v1'], corrupted);
  await button('开始部署').click();
  assert.match(await page.locator('#replace-run-current').innerText(), /存档无法读取/);
  await button('替换并开始').click();
  await page.reload();
  await resume();
  assert.deepEqual((await read()).buildings, []);
  assert.deepEqual(errors, []);

  release = await preview({ preview: { host: '127.0.0.1', port: 0 } });
  const productionPage = await browser.newPage();
  await productionPage.addInitScript(() => {
    const drawImage = CanvasRenderingContext2D.prototype.drawImage;
    window.boardPaintCount = 0;
    CanvasRenderingContext2D.prototype.drawImage = function (source, ...params) {
      if (source instanceof HTMLCanvasElement && this.canvas.parentElement?.id === 'field'
        && source.width === this.canvas.width && source.height === this.canvas.height && source.width > 300) window.boardPaintCount++;
      return drawImage.call(this, source, ...params);
    };
  });
  await productionPage.goto(`${url(release)}?sandbox=1&campaign=march&seed=42`);
  await productionPage.getByRole('button', { name: '开始部署', exact: true }).waitFor();
  assert.equal(await productionPage.locator('#open-sandbox, .sandbox').count(), 0);
  assert.equal(await productionPage.evaluate(() => typeof window.render_game_to_text), 'undefined');
  await productionPage.waitForFunction(() => document.documentElement.dataset.atlasReady === 'true' && window.boardPaintCount > 0);
  await productionPage.waitForTimeout(100);
  const idlePaints = await productionPage.evaluate(() => window.boardPaintCount);
  await productionPage.waitForTimeout(350);
  assert.equal(await productionPage.evaluate(() => window.boardPaintCount), idlePaints);
  await button('开始部署', productionPage).click();
  await productionPage.locator('#hand [data-card="watch"]').first().click();
  const beforePreview = await productionPage.evaluate(() => window.boardPaintCount);
  await productionPage.getByRole('button', { name: '6列3行 草地', exact: true }).hover();
  await productionPage.waitForFunction(before => window.boardPaintCount > before, beforePreview);
  const releaseTile = (x, y) => productionPage.getByRole('button', { name: new RegExp(`^${x}列${y}行 `) });
  const saved = () => productionPage.evaluate(() => JSON.parse(localStorage.getItem('nine-kingdoms-run-v1')).run);
  await releaseTile(6, 3).click();
  const deployed = await saved();
  await productionPage.locator('#relocate').click();
  await releaseTile(6, 4).click();
  await productionPage.reload();
  await button('继续战局', productionPage).click();
  const transferred = await saved();
  assert.deepEqual(transferred.buildings, [{ ...deployed.buildings[0], tile: { x: 5, y: 3 } }]);
  assert.equal(transferred.wallet.wood, deployed.wallet.wood - 1);
  await releaseTile(6, 4).click();
  await productionPage.locator('#remove-placement').click();
  await productionPage.locator('#confirm-removal').click();
  const cleared = await saved();
  assert.deepEqual(cleared.buildings, []);
  assert.deepEqual(cleared.wallet, transferred.wallet);
  console.log('Edge sandbox passed: refill, skip, spawn, step, isolated stats and checkpoint recovery. The release also passed idle redraw, relocation, removal, and checkpoint checks.');
} finally {
  await browser?.close();
  await dev.close();
  if (release) await new Promise(resolve => release.httpServer.close(resolve));
}
